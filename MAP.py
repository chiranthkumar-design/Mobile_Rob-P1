def print_statistics(runs_dict, planned_pts):
    """Print a summary table matching the assignment report format."""
    if not planned_pts:
        return

    planned_len = sum(
        math.hypot(planned_pts[i+1][0]-planned_pts[i][0],
                   planned_pts[i+1][1]-planned_pts[i][1])
        for i in range(len(planned_pts)-1)
    )
    straight = math.hypot(GOAL_X_MM - START_X_MM,
                          GOAL_Y_MM - START_Y_MM)

    print("\n" + "="*60)
    print("  PATH STATISTICS")
    print("="*60)
    print(f"  Planned path length : {planned_len/1000:.3f} m")
    print(f"  Straight-line dist  : {straight/1000:.3f} m")
    print(f"  Detour factor       : {planned_len/straight:.2f}×")
    print(f"  Dense waypoints     : {len(planned_pts)}")
    print(f"  Spacing             : {WP_SPACING:.0f} mm")

    if not runs_dict:
        print("\n  No actual run data found.")
        return

    print(f"\n  ACTUAL RUNS  (from astar_results.csv)")
    print(f"  {'Run':>4}  {'Points':>7}  {'Final X':>9}  "
          f"{'Final Y':>9}  {'Error mm':>10}")
    print(f"  {'-'*4}  {'-'*7}  {'-'*9}  {'-'*9}  {'-'*10}")

    errors = []
    for run_id, pts in sorted(runs_dict.items()):
        if not pts:
            continue
        fx, fy = pts[-1][0], pts[-1][1]
        err = math.hypot(fx - GOAL_X_MM, fy - GOAL_Y_MM)
        errors.append(err)
        print(f"  {run_id:>4}  {len(pts):>7}  "
              f"{fx:>9.1f}  {fy:>9.1f}  {err:>10.1f}")

    if len(errors) > 1:
        mu  = sum(errors) / len(errors)
        sig = math.sqrt(sum((e-mu)**2 for e in errors) / (len(errors)-1))
        print(f"  {'─'*50}")
        print(f"  Mean error   : {mu:.1f} mm")
        print(f"  Std deviation: {sig:.1f} mm")
        print(f"  Min error    : {min(errors):.1f} mm")
        print(f"  Max error    : {max(errors):.1f} mm")

    print("="*60)


