COLS = int(math.ceil((MAP_X2 - MAP_X1) / MAP_RES_MM)) + 2   # 103
ROWS = int(math.ceil((MAP_Y2 - MAP_Y1) / MAP_RES_MM)) + 2   # 193


def world_to_grid(x_mm: float, y_mm: float):
    """GPS-relative mm → grid (col, row).  Row 0 = north (max Y)."""
    c = int(round((x_mm - MAP_X1) / MAP_RES_MM))
    r = int(round((MAP_Y2 - y_mm) / MAP_RES_MM))
    return max(0, min(COLS-1, c)), max(0, min(ROWS-1, r))


def grid_to_world(col: int, row: int):
    """Grid (col, row) → GPS-relative mm."""
    return MAP_X1 + col * MAP_RES_MM, MAP_Y2 - row * MAP_RES_MM


