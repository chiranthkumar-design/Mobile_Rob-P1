def visualize(raw, inflated, planned_pts, runs_dict):
    """
    THREE-PANEL FIGURE (matches reference image style):

      Panel 1 — Raw Grid (Before Inflation)
                Black = wall/obstacle,  White = free space
                Grid axis labels show cell indices

      Panel 2 — Inflated Grid (Configuration Space)
                Black = obstacle + inflated margin,  White = free
                Grid axis labels show cell indices

      Panel 3 — Planned vs Actual Robot Path
                Background: inflated C-space
                Red line   = A* planned path
                Green line = Actual GPS trajectory
                Start = green circle,  Goal = blue star

    All three use equal axis scaling and grid index axes.
    """

    run_colors = [
        "#00dd77",   # run 1 — bright green
        "#00aa55",   # run 2
        "#007733",   # run 3
        "#004d22",   # run 4
        "#33ff99",   # run 5
    ]

    # ── Figure layout: 3 panels side by side ─────────────────────────────
    fig, axes = plt.subplots(1, 3, figsize=(22, 14))
    fig.patch.set_facecolor("white")
    fig.suptitle(
        "A* Path Planning — Raw Grid, Configuration Space & Planned vs Actual Path\n"
        f"Mobile Robotics M2  |  University of Salford  |  "
        f"Grid: {ROWS}×{COLS} cells  |  res={MAP_RES_MM:.0f}mm  |  inflate={INFLATE_MM:.0f}mm",
        fontsize=12, fontweight="bold", color="black", y=1.01
    )

    # ── Helper: style each axis with white background + grid index labels ─
    def style_ax(ax, title):
        ax.set_facecolor("white")
        ax.set_title(title, fontsize=12, fontweight="bold",
                     color="black", pad=8)
        ax.set_xlabel("Column index  (cells)", fontsize=9, color="#333333")
        ax.set_ylabel("Row index  (cells)",    fontsize=9, color="#333333")
        ax.tick_params(colors="#333333", labelsize=8)
        for sp in ax.spines.values():
            sp.set_edgecolor("#aaaaaa")
            sp.set_linewidth(0.8)

    # ── PANEL 1: Raw Grid (Before Inflation) ─────────────────────────────
    ax1 = axes[0]
    # imshow with origin="upper" so row 0 is at the top (matches image)
    ax1.imshow(raw, cmap="binary", origin="upper",
               interpolation="nearest", aspect="equal",
               vmin=0, vmax=1)
    style_ax(ax1, "Raw Grid (Before Inflation)")

    # Mark start and goal as small dots
    sc, sr = world_to_grid(START_X_MM, START_Y_MM)
    gc, gr = world_to_grid(GOAL_X_MM,  GOAL_Y_MM)
    ax1.plot(sc, sr, "o", color="#00cc55", markersize=9,
             markeredgecolor="black", markeredgewidth=0.8,
             zorder=5, label="Start")
    ax1.plot(gc, gr, "*", color="#0088ff", markersize=13,
             markeredgecolor="black", markeredgewidth=0.5,
             zorder=5, label="Goal")
    ax1.legend(loc="upper right", fontsize=8,
               facecolor="white", edgecolor="#aaaaaa")

    # ── PANEL 2: Inflated Grid (Configuration Space) ──────────────────────
    ax2 = axes[1]
    ax2.imshow(inflated, cmap="binary", origin="upper",
               interpolation="nearest", aspect="equal",
               vmin=0, vmax=1)
    style_ax(ax2, "Inflated Grid (Configuration Space)")

    ax2.plot(sc, sr, "o", color="#00cc55", markersize=9,
             markeredgecolor="black", markeredgewidth=0.8, zorder=5)
    ax2.plot(gc, gr, "*", color="#0088ff", markersize=13,
             markeredgecolor="black", markeredgewidth=0.5, zorder=5)

    # ── PANEL 3: Planned vs Actual Path ───────────────────────────────────
    ax3 = axes[2]

    # Background: inflated grid (black = obstacle, white = free)
    ax3.imshow(inflated, cmap="binary", origin="upper",
               interpolation="nearest", aspect="equal",
               vmin=0, vmax=1, zorder=0)
    style_ax(ax3, "Planned vs Actual Robot Path")

    # Planned A* path — convert world mm → grid indices
    if planned_pts:
        path_cols = [(world_to_grid(p[0], p[1])[0]) for p in planned_pts]
        path_rows = [(world_to_grid(p[0], p[1])[1]) for p in planned_pts]
        path_len  = sum(
            math.hypot(planned_pts[i+1][0]-planned_pts[i][0],
                       planned_pts[i+1][1]-planned_pts[i][1])
            for i in range(len(planned_pts)-1)
        )
        ax3.plot(path_cols, path_rows,
                 color="red", linewidth=1.8, zorder=3,
                 label=f"A* planned path  "
                       f"({len(planned_pts)} wps, {path_len/1000:.2f}m)")

    # Actual trajectories — per run
    for run_id, pts in sorted(runs_dict.items()):
        if not pts:
            continue
        traj_c = [world_to_grid(p[0], p[1])[0] for p in pts]
        traj_r = [world_to_grid(p[0], p[1])[1] for p in pts]
        color  = run_colors[(run_id-1) % len(run_colors)]
        ax3.plot(traj_c, traj_r,
                 color=color, linewidth=2.2,
                 zorder=4, alpha=0.9,
                 label=f"Actual trajectory  run {run_id}")

        # Direction arrows
        step = max(1, len(traj_c) // 8)
        for i in range(0, len(traj_c)-1, step):
            dc_ = traj_c[i+1] - traj_c[i]
            dr_ = traj_r[i+1] - traj_r[i]
            if abs(dc_)+abs(dr_) > 0.5:
                ax3.annotate("",
                    xy=(traj_c[i]+dc_*0.6, traj_r[i]+dr_*0.6),
                    xytext=(traj_c[i], traj_r[i]),
                    arrowprops=dict(arrowstyle="->",
                                   color=color, lw=1.1),
                    zorder=5)

    # Start / goal markers
    ax3.plot(sc, sr, "o", color="#00cc55", markersize=12,
             markeredgecolor="white", markeredgewidth=1.2,
             zorder=6, label=f"Start ({START_X_MM:.0f},{START_Y_MM:.0f})mm")
    ax3.plot(gc, gr, "*", color="#0088ff", markersize=16,
             markeredgecolor="white", markeredgewidth=0.8,
             zorder=6, label=f"Goal ({GOAL_X_MM:.0f},{GOAL_Y_MM:.0f})mm")

    # Room labels (in grid-index space)
    skip = {"Start", "Goal"}
    for lbl, x_mm, y_mm in ROOM_LABELS:
        if lbl in skip:
            continue
        lc, lr = world_to_grid(x_mm, y_mm)
        ax3.text(lc, lr, lbl,
                 fontsize=7, color="white", ha="center", va="center",
                 zorder=7,
                 bbox=dict(boxstyle="round,pad=0.2",
                           fc="#222255", ec="#8888cc",
                           lw=0.6, alpha=0.80))

    # Error annotation for run 1
    if 1 in runs_dict and runs_dict[1]:
        last  = runs_dict[1][-1]
        lc, lr = world_to_grid(last[0], last[1])
        err_mm = math.hypot(last[0]-GOAL_X_MM, last[1]-GOAL_Y_MM)
        ax3.annotate(f"Final err\n{err_mm:.0f} mm",
                     xy=(lc, lr),
                     xytext=(lc+5, lr+8),
                     fontsize=8, color="#ffcc00",
                     arrowprops=dict(arrowstyle="->",
                                    color="#ffcc00", lw=1.0),
                     bbox=dict(boxstyle="round,pad=0.2",
                               fc="#332200", ec="#ffcc00",
                               lw=0.7, alpha=0.88),
                     zorder=8)

    ax3.legend(loc="lower right", fontsize=8,
               facecolor="white", edgecolor="#aaaaaa",
               labelcolor="black", framealpha=0.92)

    # ── Save ──────────────────────────────────────────────────────────────
    plt.tight_layout(pad=1.5)
    plt.savefig(OUTPUT_PNG, dpi=180, bbox_inches="tight",
                facecolor=fig.get_facecolor())
    print(f"\n[SAVED] {OUTPUT_PNG}")
    plt.show()


