def load_csv():
    """
    Load astar_results.csv.

    CSV columns (from contribution1_astar_v7.py):
      run, event, mode, x_mm, y_mm, th_deg,
      goal_x_mm, goal_y_mm, error_mm,
      time_s, path_mm, n_waypoints, plan_ms

    Returns:
      runs_dict : {run_id: [(x_mm, y_mm, time_s, event), ...]}
      all_pts   : [(x_mm, y_mm), ...] all positions across all runs
    """
    csv_path = None
    for candidate in CSV_CANDIDATES:
        if os.path.isfile(candidate):
            csv_path = candidate
            break

    if csv_path is None:
        print("[CSV] WARNING: astar_results.csv not found in:")
        for c in CSV_CANDIDATES:
            print(f"        {c}")
        print("[CSV] Plotting planned path only (no actual trajectory).")
        return {}, []

    print(f"[CSV] Loading: {csv_path}")
    runs_dict = {}
    all_pts   = []

    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)

        # Normalise column names (strip whitespace)
        reader.fieldnames = [n.strip() for n in (reader.fieldnames or [])]

        for row in reader:
            try:
                run    = int(row.get("run", 0))
                event  = row.get("event", "").strip()
                x_mm   = float(row.get("x_mm",   row.get("x", 0)))
                y_mm   = float(row.get("y_mm",   row.get("y", 0)))
                t_s    = float(row.get("time_s", 0))

                if run not in runs_dict:
                    runs_dict[run] = []
                runs_dict[run].append((x_mm, y_mm, t_s, event))
                all_pts.append((x_mm, y_mm))
            except (ValueError, KeyError):
                continue   # skip header / bad rows

    n_runs = len(runs_dict)
    n_pts  = len(all_pts)
    print(f"[CSV] Loaded {n_pts} rows across {n_runs} run(s)")
    for run_id, pts in sorted(runs_dict.items()):
        events = [e for _,_,_,e in pts]
        print(f"       Run {run_id}: {len(pts)} points  "
              f"events={events}")
    return runs_dict, all_pts


