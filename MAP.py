def make_grid_rgb(raw, inflated):
    """
    Build an RGB image for the occupancy grid background.
      White       = free space
      Light grey  = inflated margin
      Dark grey   = actual wall/obstacle
    """
    h, w = raw.shape
    rgb  = np.ones((h, w, 3), dtype=float)

    # Inflated margin (where raw=0 but inflated=1)
    margin_mask          = (inflated == 1) & (raw == 0)
    rgb[margin_mask]     = [0.72, 0.72, 0.76]

    # Actual wall / obstacle
    wall_mask            = (raw == 1)
    rgb[wall_mask]       = [0.18, 0.18, 0.20]

    # Flip so y increases upward in the plot
    return np.flipud(rgb)


